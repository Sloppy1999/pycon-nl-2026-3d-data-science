"""Merge the three research parts into deck/ecosystem/ecosystem.yaml (the catalogue the deck and docs/ECOSYSTEM.md read).

    cd talk && uv run python deck/ecosystem/merge.py

part1.yaml (data, numerics, geospatial), part2.yaml (processing, reconstruction, CAD) and part3.yaml (visualisation,
applications, deep learning, organisations) were written by three researchers on 2026-10-11; every fact in them
was fetched from PyPI, GitHub or the project site (the `evidence` list of each entry). Where two parts list the same
id, the entry that has a logo file wins and the other fills in missing fields. Hand fixes live in overrides.yaml,
never in the parts, so a re-run keeps them.
"""

from __future__ import annotations

import datetime as dt
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
LOGOS = HERE.parent / "assets" / "logos"


def norm(v):
    if isinstance(v, (dt.date, dt.datetime)):
        return v.isoformat()[:10]
    if isinstance(v, dict):
        return {k: norm(x) for k, x in v.items()}
    if isinstance(v, list):
        return [norm(x) for x in v]
    return v


def has_logo(e) -> bool:
    l = e.get("logo")
    return bool(l and (LOGOS / l["file"]).is_file())


def merge(kind: str, parts: list[dict]) -> list[dict]:
    out: dict[str, dict] = {}
    for p in parts:
        for e in p.get(kind, []):
            e = norm(e)
            old = out.get(e["id"])
            if old is None:
                out[e["id"]] = e
                continue
            a, b = (old, e) if has_logo(old) or not has_logo(e) else (e, old)
            for k, v in b.items():
                if a.get(k) in (None, "", "unverified") and v not in (None, ""):
                    a[k] = v
            a.setdefault("merged_from", []).append("duplicate id in two parts")
            out[e["id"]] = a
    return list(out.values())


def main() -> int:
    parts = [yaml.safe_load((HERE / f"part{i}.yaml").read_text()) for i in (1, 2, 3)]
    entries, orgs = merge("entries", parts), merge("orgs", parts)
    ov_path = HERE / "overrides.yaml"
    ov = yaml.safe_load(ov_path.read_text()) if ov_path.exists() else {}
    by = {e["id"]: e for e in entries + orgs}
    for key, fields in (ov.get("set") or {}).items():
        by[key].update(fields)
    for key in ov.get("drop") or []:
        entries[:] = [e for e in entries if e["id"] != key]
        orgs[:] = [e for e in orgs if e["id"] != key]
    for e in entries + orgs:                      # a logo whose file is gone is no logo
        if e.get("logo") and not has_logo(e):
            e["logo"] = None
    out = {"generated_by": "deck/ecosystem/merge.py", "entries": entries, "orgs": orgs}
    (HERE / "ecosystem.yaml").write_text(yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=120))
    n_logo = sum(has_logo(e) for e in entries + orgs)
    write_results(entries, orgs)
    write_docs(entries, orgs)
    write_logo_sources(entries, orgs)
    print(f"{len(entries)} entries, {len(orgs)} orgs, {n_logo} with a logo file")
    return 0


TALK = HERE.parents[1]
GROUPS = [("data_io", "Load, store and exchange point clouds"), ("numerics", "Arrays, tables and scale"),
          ("geospatial", "Geospatial"), ("processing", "Point cloud and mesh processing"),
          ("reconstruction", "Registration, photogrammetry and reconstruction"),
          ("cad_volumetric", "CAD, BIM and volumetric data"), ("visualisation", "Visualisation"),
          ("applications", "Applications next to Python"), ("deep_learning", "Deep learning for 3D"),
          ("simulation", "Differentiable graphics and simulation")]


def write_results(entries, orgs):
    """results/ecosystem.json: counts and per-id status for the deck's {eco.*} tokens (no hand-typed numbers)."""
    import json
    by_status: dict[str, int] = {}
    for e in entries:
        by_status[e["status"]] = by_status.get(e["status"], 0) + 1
    out = {"label": "FINAL", "script": "deck/ecosystem/merge.py", "verified_on": "2026-10-11",
           "n_entries": len(entries), "n_orgs": len(orgs), "n_logos": sum(has_logo(e) for e in entries + orgs),
           "by_status": by_status,
           "by_id": {e["id"]: {k: e.get(k) for k in ("name", "status", "latest_version", "last_release", "licence")}
                     for e in entries}}
    (TALK / "results" / "ecosystem.json").write_text(json.dumps(out, indent=2) + "\n")


def write_docs(entries, orgs):
    L = ["# The Python 3D ecosystem: where to look", "",
         "Generated by `deck/ecosystem/merge.py` from `deck/ecosystem/ecosystem.yaml` (do not edit by hand). Every row",
         "was checked on 2026-10-11 against PyPI and GitHub (the evidence links are in the YAML); the status is",
         "**active** (release within 12 months), **maintenance** (12 to 30 months), **stale** (older) or **archived**.",
         "`unverified` means the field could not be checked. This is a map for finding libraries, not a ranking and not",
         "a recommendation: check the repository before you depend on anything.", ""]
    for gid, title in GROUPS:
        rows = [e for e in entries if e["group"] == gid]
        if not rows:
            continue
        L += [f"## {title}", "", "| Name | What it does | Status | Latest release | Licence | Behind it |", "|---|---|---|---|---|---|"]
        for e in sorted(rows, key=lambda e: e["name"].lower()):
            url = e.get("home_url") or e.get("repo_url") or ""
            nm = f"[{e['name']}]({url})" if url and url != "unverified" else e["name"]
            rel = f"{e.get('latest_version', 'unverified')} ({e.get('last_release', 'unverified')})"
            L.append(f"| {nm} | {e.get('summary', '')} | {e['status']} | {rel} | {e.get('licence', 'unverified')} | {e.get('org', '')} |")
        L.append("")
    L += ["## Companies and foundations", "", "| Name | Type | What they do here |", "|---|---|---|"]
    for o in sorted(orgs, key=lambda o: o["name"].lower()):
        L.append(f"| [{o['name']}]({o.get('home_url', '')}) | {o.get('org_type', '')} | {o.get('what', '')} |")
    L += ["", "## Logos", "", "Logos on slide 3 belong to their owners and are shown to identify the projects and companies; no",
          "endorsement is implied. Sources, stated terms and brand-policy notes per file: "
          "[deck/assets/logos/SOURCES.md](../deck/assets/logos/SOURCES.md).", ""]
    (TALK / "docs" / "ECOSYSTEM.md").write_text("\n".join(L))


def write_logo_sources(entries, orgs):
    L = ["# Logo sources and terms", "", "Generated by `deck/ecosystem/merge.py`. Logos are shown unaltered (scaled only) on",
         "slide 3 to identify projects and the companies behind them. They are trademarks or copyrights of their owners;",
         "no endorsement is implied. `terms` is what the source states; `policy` is what the brand page says, as the",
         "researcher read it on 2026-10-11 (a 403 or missing page means it was NOT read). Check the owners' current brand",
         "rules before the slides are published or recorded.", "",
         "| Id | File | Kind | Source | Terms | Policy |", "|---|---|---|---|---|---|"]
    for e in entries + orgs:
        l = e.get("logo")
        if not l or not has_logo(e):
            continue
        pol = (l.get("brand_guidelines_url") or "none found") + ": " + (l.get("restriction_note") or "none found")
        L.append(f"| {e['id']} | {l['file']} | {l.get('kind', '')} | {l.get('source_url', '')} | "
                 f"{l.get('licence_or_terms', '')} | {pol} |".replace("\n", " "))
    (LOGOS / "SOURCES.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    raise SystemExit(main())
