"""Layout geometry of the PyCon NL 2026 master, read from the template's own layouts (no hard-coded coordinates).

Every builder position derives from the placeholders of deck/template/pycon_nl_2026_master.pptx (generated by
deck/template/make_master.py, documented in docs/DESIGN.md section 5): the 0.600 in outer margin, the content
area, the two L5 columns, the L7/L8 text column and media frame, the L10 title and content columns, and the
L1/L11 zones (presenter, logo, contact, QR, small print).

    from lib.geometry import GEO
    GEO.ph(7, 18)        # Box(x, y, w, h) in inches of layout 7's media placeholder (idx 18)
    GEO.title(7)         # layout 7's title box
    GEO.content_top(7, 2)  # first content y under a two-line title on layout 7

Layout numbers are 1-based, as in content.yaml.
"""

from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from pathlib import Path

from pptx import Presentation

EMU_IN = 914400
TEMPLATE = Path(__file__).resolve().parents[1] / "template" / "pycon_nl_2026_master.pptx"
TITLE_GAP = 0.283      # clear space between the title box bottom and the content (DESIGN.md: 2.150 - 1.867)


@dataclass(frozen=True)
class Box:
    x: float
    y: float
    w: float
    h: float

    @property
    def x2(self) -> float:
        return self.x + self.w

    @property
    def y2(self) -> float:
        return self.y + self.h

    def t(self) -> tuple[float, float, float, float]:
        return (self.x, self.y, self.w, self.h)


def _box(sh) -> Box:
    return Box(sh.left / EMU_IN, sh.top / EMU_IN, sh.width / EMU_IN, sh.height / EMU_IN)


class Geometry:
    def __init__(self, template: Path = TEMPLATE):
        prs = Presentation(str(template))
        self.slide_w = prs.slide_width / EMU_IN
        self.slide_h = prs.slide_height / EMU_IN
        self.layout_names: dict[int, str] = {}
        self._ph: dict[int, dict[int, Box]] = {}
        self._title: dict[int, Box] = {}
        self._bar: dict[int, Box] = {}
        for li, lay in enumerate(prs.slide_layouts, 1):
            self.layout_names[li] = lay.name
            phs = {}
            for sh in lay.placeholders:
                idx = sh.placeholder_format.idx
                b = _box(sh)
                if sh.placeholder_format.type is not None and idx == 0:
                    self._title[li] = b
                phs[idx] = b
            self._ph[li] = phs
            for sh in lay.shapes:
                if sh.is_placeholder:
                    continue
                if sh.name == "Accent bar":
                    self._bar[li] = _box(sh)
        body = self.ph(4, 1)
        self.margin = body.x                       # 0.600
        self.content_w = body.w                    # 12.133
        self.right = body.x2                       # 12.733
        self.bottom = body.y2                      # 6.800: content bottom on every white layout
        left, right = self.ph(5, 1), self.ph(5, 2)
        self.col_w = left.w                        # L5 column width
        self.col_gap = right.x - left.x2           # 0.500
        self.col_r = right.x
        self.footer = self.ph(4, 11)
        self.slide_number = self.ph(4, 12)

    # -- lookups ----------------------------------------------------------------------------------------------
    def ph(self, layout: int, idx: int) -> Box:
        try:
            return self._ph[layout][idx]
        except KeyError:
            raise KeyError(f"layout {layout} ({self.layout_names.get(layout)}) has no placeholder idx {idx}") from None

    def has(self, layout: int, idx: int) -> bool:
        return idx in self._ph.get(layout, {})

    def title(self, layout: int) -> Box:
        return self._title[layout]

    def bar(self, layout: int) -> Box | None:
        return self._bar.get(layout)

    def body(self, layout: int) -> Box:
        """The layout's main content placeholder: idx 1 (L2 to L6, L10), idx 14 (L7, L8) or idx 18 (L9)."""
        for idx in (14, 1, 18):
            if self.has(layout, idx):
                return self.ph(layout, idx)
        raise KeyError(f"layout {layout} has no content placeholder")

    def content_top(self, layout: int, title_lines: int, title_pt: float = 32.0) -> float:
        """First content y: the layout's content top, or lower when the title runs to more lines than the layout
        plans for (title top + lines x 1.2 em + TITLE_GAP)."""
        t = self.title(layout)
        need = t.y + max(1, title_lines) * title_pt * 1.2 / 72 + TITLE_GAP
        try:
            top = self.body(layout).y
        except KeyError:
            top = need
        return max(top, round(need, 4))


@lru_cache(maxsize=None)
def load(template: str | None = None) -> Geometry:
    return Geometry(Path(template) if template else TEMPLATE)


GEO = load()
